"""Generate the cell certificates for Stage 5's menu circuits (SubsetsumLean/Stage5Probs.lean, Stage5Cells_*.lean).

Pure standard library. Same method and checker as Stage 4 (gen_stage4_cells.py, `SS4.chk`): the colour polygon is
covered by a binary tree of boxes, each leaf bounded by Gibbs tangent planes and a chord, checked by `decide +kernel`.
The problems are the contact claims V(t1) <= t1 hsLo and V(t2) <= (1 - t2)(1 - s) of the seven circuits of
certificates/stage5/cert_stage5.py MENU_DATA. The circuit s = 1/8 is Stage 4's own (same rho, t1, t2: asserted below),
so its trees are reused from Stage4Cells_s8_*; the six others are new here.
Run:  python3 gen_stage5_cells.py   (writes Stage5Probs.lean, the Stage5Cells_* modules and stage5_modules.txt)
"""
from fractions import Fraction as F
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "certificates", "stage5"))
import gen_stage4_cells as G  # noqa: E402

sys.dont_write_bytecode = True


def tag_of(s):
    """Short name of a menu circuit: m + the first digits of s (2/25 -> m80, 19/200 -> m95, ...)."""
    return "m" + str(int(F(s) * 1000))


def menu():
    """MENU_DATA of cert_stage5.py, read from the source (importing it would import the vendored Stage 4 cert)."""
    import ast
    src = open(os.path.join(HERE, "..", "certificates", "stage5", "cert_stage5.py")).read()
    start = src.index("MENU_DATA = [")
    end = src.index("]\n", start) + 1
    node = ast.parse(src[start:end]).body[0].value
    out = []
    for tup in node.elts:
        vals = []
        for e in tup.elts:
            vals.append(F(eval(compile(ast.Expression(e), "<menu>", "eval"), {"F": F})))
        out.append(tuple(vals))
    return out


def problems():
    """(name, s, rho, tau, target, doc) of the twelve new contact claims."""
    out = []
    for s, rho, t1, t2 in menu():
        if s == F(1, 8):
            # Stage 4's s = 1/8 circuit: the same claims, already in Stage4Cells_s8_t1 / _t2.
            assert (rho, t1, t2) == (F(27, 10), F(798773, 2500000), F(7218613, 10 ** 7))
            continue
        hlo, _ = G.hb_bounds(s)
        tag = tag_of(s)
        out.append((f"{tag}_t1", s, rho, t1, t1 * hlo, "V(t1) <= t1 hsLo"))
        out.append((f"{tag}_t2", s, rho, t2, (1 - t2) * (1 - s), "V(t2) <= (1-t2)(1-s)"))
    return out


def main():
    mods = []
    probs = ["import SubsetsumLean.Stage4Check", "",
             "/-! The twelve new contact problems of Stage 5's menu circuits (generated by `gen_stage5_cells.py`; do "
             "not edit). -/", "", "namespace SS5", "", "open SS4", ""]
    only = set(sys.argv[1:])
    for name, s, rho, tau, T, doc in problems():
        k = F(s) / 2
        P = dict(k=k, rho=F(rho), tau=F(tau), T=F(T))
        assert G.prob_ok(P)
        probs += [f"/-- {doc}: s = {s}, rho = {rho}, tau = {tau}, target = {T}. -/",
                  f"def P_{name} : Prob := ⟨{G.q(P['k'])}, {G.q(P['rho'])}, {G.q(P['tau'])}, {G.q(P['T'])}⟩",
                  f"theorem prob_{name} : P_{name}.ok = true := by decide +kernel", ""]
        if only and name not in only:
            continue
        root = (k, 2 * k, k, G.bq(P, 2 * k))
        t = G.build(P, *root)
        assert G.chk(P, t, *root)
        nl, nn, ns = G.count(t)
        print(f"{name}: {nl} leaves, {nn} empty, {ns} splits", flush=True)
        parts = []
        sk = G.chunks(t, root, P, "", parts)
        pm = []
        for i, (sub, box) in enumerate(parts):
            out = []
            G.lean_tree(sub, out)
            mod = f"Stage5Cells_{name}_{i}"
            pm.append(mod)
            with open(os.path.join(HERE, "SubsetsumLean", mod + ".lean"), "w") as f:
                f.write(f"""import SubsetsumLean.Stage5Probs

/-! Cell certificate `{name}`, part {i} of {len(parts)} (generated by `gen_stage5_cells.py`; do not edit). -/

namespace SS5

open SS4

def T_{name}_{i} : CT := {"".join(out)}

theorem c_{name}_{i} : chk P_{name} T_{name}_{i} {" ".join(G.q(x) for x in box)} = true := by
  decide +kernel

end SS5
""")
        mods.extend(pm)
        root_q = " ".join(G.q(x) for x in root)
        with open(os.path.join(HERE, "SubsetsumLean", f"Stage5Cells_{name}.lean"), "w") as f:
            f.write("\n".join(f"import SubsetsumLean.{m}" for m in pm) + f"""

/-! Cell certificate `{name}` assembled from its {len(parts)} parts ({doc}; generated by `gen_stage5_cells.py`). -/

namespace SS5

open SS4

def T_{name} : CT := {G.skel_term(sk, name)}

theorem cells_{name} : chk P_{name} T_{name} {root_q} = true :=
  {G.skel_proof(sk, name, P, 2)}

end SS5
""")
        mods.append(f"Stage5Cells_{name}")
    probs.append("end SS5")
    with open(os.path.join(HERE, "SubsetsumLean", "Stage5Probs.lean"), "w") as f:
        f.write("\n".join(probs) + "\n")
    if not only:
        with open(os.path.join(HERE, "stage5_modules.txt"), "w") as f:
            f.write("\n".join(["Stage5Probs"] + mods) + "\n")


if __name__ == "__main__":
    main()
