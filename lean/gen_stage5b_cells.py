"""Generate the cell certificates for Stage 5b's family circuits (SubsetsumLean/Stage5bProbs.lean, Stage5bCells_*.lean).

Pure standard library. Same method and checker as Stage 4 (gen_stage4_cells.py, `SS4.chk`): the colour polygon is
covered by a binary tree of boxes, each leaf bounded by Gibbs tangent planes and a chord, checked by `decide +kernel`.
The problems are the six member statements of Lemma 5b.1 for each of the six families that row R4b-min uses:
member i is below the line at both ends of its interval, V_rho_i(v_{i-1}) <= line(v_{i-1}) and V_rho_i(v_i) <= line(v_i),
with line(tau) = r + (l - r) tau, all from FAM_DATA of the Stage 5b certificate (CERT_DIR/cert_stage5b.py).
Run:  python3 gen_stage5b_cells.py   (writes Stage5bProbs.lean, the Stage5bCells_* modules and stage5b_modules.txt)
"""
from fractions import Fraction as F
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CERT_DIR = os.path.join(HERE, "..", "certificates", "stage5b")
sys.path.insert(0, HERE)
sys.dont_write_bytecode = True
import gen_stage4_cells as G  # noqa: E402

# The families of row R4b-min (FAMILY_DENSITIES of cert_stage5b.py); the other two densities use Stage 5's circuits.
USED = (F(13, 125), F(111, 1000), F(59, 500), F(1, 8), F(29, 200), F(11, 100))


def fam_tag(s):
    """Short name of a family: f + the first digits of s (13/125 -> f104, 1/8 -> f125, ...)."""
    return "f" + str(int(F(s) * 1000))


def _literal(name):
    """A top-level literal assignment of cert_stage5b.py, read from the source (importing it would run its imports)."""
    src = open(os.path.join(CERT_DIR, "cert_stage5b.py")).read()
    start = src.index(f"{name} = ")
    node = None
    for end in range(src.index("\n", start), len(src)):
        if src[end] != "\n":
            continue
        try:
            node = ast.parse(src[start:end]).body[0].value
            break
        except SyntaxError:
            continue
    return eval(compile(ast.Expression(node), "<cert>", "eval"), {"F": F, "dict": dict})


def fam_data():
    data = _literal("FAM_DATA")
    used = _literal("FAMILY_DENSITIES")
    assert tuple(used) == USED, "FAMILY_DENSITIES of cert_stage5b.py changed"
    return {s: data[s] for s in USED}


def line(D, v):
    return D["r"] + (D["l"] - D["r"]) * F(v)


def problems():
    """(name, s, rho, tau, target, doc) of the 36 member statements."""
    out = []
    for s, D in fam_data().items():
        rhos, bps = D["rhos"], D["bps"]
        assert len(rhos) == 3 and len(bps) == 4 and list(bps) == sorted(set(bps))
        for i, rho in enumerate(rhos):
            for e, v in (("a", bps[i]), ("b", bps[i + 1])):
                out.append((f"{fam_tag(s)}_{i + 1}{e}", s, rho, v, line(D, v), f"V_{rho}({v}) <= line({v})"))
    return out


def main():
    mods = []
    probs = ["import SubsetsumLean.Stage4Check", "",
             "/-! The 36 member statements of Stage 5b's six families (Lemma 5b.1; generated by `gen_stage5b_cells.py`; "
             "do not edit). -/", "", "namespace SS5b", "", "open SS4", ""]
    only = set(sys.argv[1:])
    for name, s, rho, tau, T, doc in problems():
        k = F(s) / 2
        P = dict(k=k, rho=F(rho), tau=F(tau), T=F(T))
        assert G.prob_ok(P)
        probs += [f"/-- {doc}: s = {s}, rho = {rho}, tau = {tau}, target = {T}. -/",
                  f"def P_{name} : Prob := ⟨{G.q(P['k'])}, {G.q(P['rho'])}, {G.q(P['tau'])}, {G.q(P['T'])}⟩",
                  f"theorem prob_{name} : P_{name}.ok = true := by decide +kernel", ""]
        if only and name not in only:
            continue
        root = (k, 2 * k, k, G.bq(P, 2 * k))
        t = G.build(P, *root)
        assert G.chk(P, t, *root)
        nl, nn, ns = G.count(t)
        print(f"{name}: {nl} leaves, {nn} empty, {ns} splits", flush=True)
        parts = []
        sk = G.chunks(t, root, P, "", parts)
        pm = []
        for i, (sub, box) in enumerate(parts):
            out = []
            G.lean_tree(sub, out)
            mod = f"Stage5bCells_{name}_{i}"
            pm.append(mod)
            with open(os.path.join(HERE, "SubsetsumLean", mod + ".lean"), "w") as f:
                f.write(f"""import SubsetsumLean.Stage5bProbs

/-! Cell certificate `{name}`, part {i} of {len(parts)} (generated by `gen_stage5b_cells.py`; do not edit). -/

namespace SS5b

open SS4

def T_{name}_{i} : CT := {"".join(out)}

theorem c_{name}_{i} : chk P_{name} T_{name}_{i} {" ".join(G.q(x) for x in box)} = true := by
  decide +kernel

end SS5b
""")
        mods.extend(pm)
        root_q = " ".join(G.q(x) for x in root)
        with open(os.path.join(HERE, "SubsetsumLean", f"Stage5bCells_{name}.lean"), "w") as f:
            f.write("\n".join(f"import SubsetsumLean.{m}" for m in pm) + f"""

/-! Cell certificate `{name}` assembled from its {len(parts)} parts ({doc}; generated by `gen_stage5b_cells.py`). -/

namespace SS5b

open SS4

def T_{name} : CT := {G.skel_term(sk, name)}

theorem cells_{name} : chk P_{name} T_{name} {root_q} = true :=
  {G.skel_proof(sk, name, P, 2)}

end SS5b
""")
        mods.append(f"Stage5bCells_{name}")
    probs.append("end SS5b")
    with open(os.path.join(HERE, "SubsetsumLean", "Stage5bProbs.lean"), "w") as f:
        f.write("\n".join(probs) + "\n")
    if not only:
        with open(os.path.join(HERE, "stage5b_modules.txt"), "w") as f:
            f.write("\n".join(["Stage5bProbs"] + mods) + "\n")


if __name__ == "__main__":
    main()
